"""
Generate the PlatformIO build tree from the canonical sources.

PlatformIO compiles what it finds under src/. Rather than keep a second copy of
the firmware there by hand, this mirrors sketch.ino -> src/main.cpp (with an
explicit Arduino.h, since .cpp gets no implicit prototypes) and copies
config.h alongside it. Generated: edit the root files and re-run.

    python tools/make_pio_src.py

Pass --lite to build wokwi/sketch_lite.ino instead (2 libraries, fast build).
"""

import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src")

HEADER = """// ============================================================================
//  GENERATED by tools/make_pio_src.py from {origin} - do not edit.
//  Edit the source above and re-run, or the copies will drift apart.
// ============================================================================
#include <Arduino.h>

"""


def main():
    lite = "--lite" in sys.argv
    origin = "wokwi/sketch_lite.ino" if lite else "sketch.ino"
    src_path = os.path.join(ROOT, *origin.split("/"))

    body = io.open(src_path, encoding="utf-8").read()
    os.makedirs(SRC, exist_ok=True)

    # The full build keeps its settings in config.h; the lite build inlines them.
    if not lite:
        config = io.open(os.path.join(ROOT, "config.h"), encoding="utf-8").read()
        io.open(os.path.join(SRC, "config.h"), "w", encoding="utf-8",
                newline="\n").write(config)
    else:
        stale = os.path.join(SRC, "config.h")
        if os.path.exists(stale):
            os.remove(stale)

    out = os.path.join(SRC, "main.cpp")
    io.open(out, "w", encoding="utf-8", newline="\n").write(
        HEADER.format(origin=origin) + body
    )
    print(f"wrote {out} from {origin} ({len(body.splitlines())} lines)")


if __name__ == "__main__":
    main()
