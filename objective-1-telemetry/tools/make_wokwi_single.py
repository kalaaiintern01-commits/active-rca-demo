"""
Generate a single-file sketch for the wokwi.com editor.

The newer Wokwi UI makes adding a second source file awkward (and replaces
libraries.txt with the Library Manager), so this inlines config.h into
sketch.ino and writes wokwi/sketch.ino. Generated, never hand-edited: edit
config.h / sketch.ino and re-run, so the two versions cannot drift apart.

    python tools/make_wokwi_single.py
"""

import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_DIR = os.path.join(ROOT, "wokwi")
OUT = os.path.join(OUT_DIR, "sketch.ino")

BANNER = """// ============================================================================
//  config.h - INLINED for the wokwi.com single-file editor.
//  Generated by tools/make_wokwi_single.py from config.h - do not edit here;
//  edit config.h and re-run, or the two copies will drift.
// ============================================================================
"""

END = """// ============================================================================
//  end of inlined config.h
// ============================================================================
"""


def main():
    sketch = io.open(os.path.join(ROOT, "sketch.ino"), encoding="utf-8").read()
    config = io.open(os.path.join(ROOT, "config.h"), encoding="utf-8").read()

    # #pragma once is meaningless once the text is pasted inline
    config = "\n".join(
        ln for ln in config.splitlines() if ln.strip() != "#pragma once"
    ).strip()

    marker = '#include "config.h"'
    if marker not in sketch:
        raise SystemExit(f"marker {marker!r} not found in sketch.ino")

    merged = sketch.replace(marker, BANNER + config + "\n" + END, 1)

    # The web editor is filled from the clipboard, so keep the generated source
    # pure ASCII and no encoding surprise can reach the compiler.
    for uni, plain in (
        ("—", "-"), ("–", "-"), ("·", "-"), ("→", "->"),
        ("°", " deg"), ("±", "+/-"), ("µ", "u"),
        ("Ω", "ohm"), ("²", "^2"),
    ):
        merged = merged.replace(uni, plain)

    residual = sorted({c for c in merged if ord(c) > 127})
    if residual:
        raise SystemExit(f"unmapped non-ASCII characters: {residual}")

    os.makedirs(OUT_DIR, exist_ok=True)
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(merged)
    print(f"wrote {OUT}  ({len(merged.splitlines())} lines, {len(merged)} bytes)")


if __name__ == "__main__":
    main()
